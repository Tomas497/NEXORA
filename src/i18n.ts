export function getTranslation(lang: Language, section: string, key: string, params?: Record<string, any>): string {
  const langDict = TRANSLATIONS[lang] || TRANSLATIONS.es;
  const secDict = langDict[section] || TRANSLATIONS.es[section];
  let text = secDict?.[key] || TRANSLATIONS.es[section]?.[key] || key;

  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`{${k}}`, 'g'), String(v));
    });
  }

  return text;
}
